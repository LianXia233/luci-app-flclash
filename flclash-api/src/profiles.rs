//! Profile store: import / update / apply / edit / delete plus the payload
//! rendering with real counters. All writes go through the conversion engine,
//! so every stored profile is core-loadable.

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

use crate::config::write_atomic;
use crate::convert::{convert_subscription, count_top_level_list, fetch_profile};
use crate::state::{human_age, human_bytes, now_secs, AppState};

#[derive(Debug, Clone, Default, serde::Serialize, serde::Deserialize)]
pub struct Profile {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub name: String,
    #[serde(rename = "type", default)]
    pub ptype: String,
    #[serde(default)]
    pub url: String,
    #[serde(default)]
    pub updated_at: i64,
    #[serde(default)]
    pub interval: i64,
    #[serde(default)]
    pub used: i64,
    #[serde(default)]
    pub total: i64,
    #[serde(default)]
    pub expire: i64,
    /// Subscription request options (FlClash-compatible).
    #[serde(default)]
    pub user_agent: String,
    #[serde(default)]
    pub timeout: i64,
    #[serde(default)]
    pub retry: i64,
    #[serde(default)]
    pub last_error: String,
    #[serde(default)]
    pub last_success: i64,
    #[serde(default)]
    pub active: bool,
}

pub fn load_profiles(st: &AppState) -> Vec<Profile> {
    match std::fs::read(&st.index_path()) {
        Ok(data) => serde_json::from_slice(&data).unwrap_or_default(),
        Err(_) => Vec::new(),
    }
}

pub fn save_profiles(st: &AppState, list: &[Profile]) -> Result<(), String> {
    std::fs::create_dir_all(st.profiles_dir())
        .map_err(|e| format!("mkdir profiles: {}", e))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(
            st.profiles_dir(),
            std::fs::Permissions::from_mode(0o700),
        );
    }
    let data = serde_json::to_vec_pretty(list).map_err(|e| e.to_string())?;
    // Atomic: a power cut mid-write must not leave an unparseable index (which
    // load_profiles would silently treat as "no profiles").
    write_atomic(&st.index_path(), &data)
}

/// Shared host check for subscription URLs and every redirect hop: blocks
/// loopback / link-local / multicast / unspecified literals and localhost
/// names. Private LAN hosts stay allowed (self-hosted subscriptions are a
/// real use case); DNS names that *resolve* into a blocked range are not
/// caught — the import runs as the router itself, so this is a guard against
/// cloud-metadata-style probes, not a full SSRF sandbox.
pub fn host_blocked(host: &str) -> bool {
    if host.eq_ignore_ascii_case("localhost") || host.to_ascii_lowercase().ends_with(".localhost") {
        return true;
    }
    if let Ok(ip) = host.parse::<std::net::IpAddr>() {
        return match ip {
            std::net::IpAddr::V4(v4) => {
                v4.is_loopback()
                    || v4.is_unspecified()
                    || v4.is_link_local()
                    || v4.is_broadcast()
                    || v4.is_multicast()
            }
            std::net::IpAddr::V6(v6) => {
                v6.is_loopback()
                    || v6.is_unspecified()
                    || v6.is_multicast()
                    || (v6.segments()[0] & 0xffc0) == 0xfe80
            }
        };
    }
    false
}

/// Rejects subscription URLs that point at loopback / link-local addresses.
pub fn validate_subscription_url(url: &str) -> Result<(), String> {
    if url.len() > 2048 {
        return Err("订阅地址过长".into());
    }
    let rest = url
        .strip_prefix("https://")
        .or_else(|| url.strip_prefix("http://"))
        .or_else(|| url.strip_prefix("HTTPS://"))
        .or_else(|| url.strip_prefix("HTTP://"))
        .ok_or_else(|| "订阅地址必须是 http(s)://".to_string())?;
    let authority = rest
        .split(['/', '?', '#'])
        .next()
        .unwrap_or("")
        .rsplit('@') // drop userinfo
        .next()
        .unwrap_or("");
    let host = if let Some(stripped) = authority.strip_prefix('[') {
        stripped.split(']').next().unwrap_or("")
    } else {
        authority.split(':').next().unwrap_or("")
    };
    if host.is_empty() {
        return Err("订阅地址缺少主机名".into());
    }
    if host_blocked(host) {
        return Err("不允许订阅回环/链路本地地址".into());
    }
    Ok(())
}

/// Profile ids are generated by `import_profile` as `p<nanos>`. Anything else
/// reaches the store through a URL path segment, which is user-controlled (and
/// percent-decoded by axum), so it must never be joined into a filesystem path.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// Safe absolute path for a profile YAML, or `None` for an invalid id.
pub fn profile_path(st: &AppState, id: &str) -> Option<PathBuf> {
    valid_id(id).then(|| st.profiles_dir().join(format!("{}.yaml", id)))
}

fn profile_file(st: &AppState, id: &str) -> PathBuf {
    if !valid_id(id) {
        // Unreachable through the API (handlers reject first); fail closed for
        // a tampered index.json instead of escaping the profiles directory.
        return st.profiles_dir().join("__invalid__");
    }
    st.profiles_dir().join(format!("{}.yaml", id))
}

/// Counts (proxies, groups, rules) for a stored profile, cached by mtime.
///
/// `/status` rebuilds the active profile payload every two seconds. Re-reading
/// a multi-megabyte subscription each time was pure waste; the counts only
/// change when the file is rewritten (import/update/edit all replace it).
fn profile_counts(path: &Path) -> (usize, usize, usize) {
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};

    static CACHE: OnceLock<Mutex<HashMap<String, (u64, (usize, usize, usize))>>> = OnceLock::new();
    let stamp = std::fs::metadata(path)
        .and_then(|meta| meta.modified())
        .ok()
        .and_then(|time| time.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0);
    let key = path.to_string_lossy().into_owned();
    if stamp != 0 {
        let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
        if let Some((cached_stamp, counts)) = cache.lock().unwrap().get(&key) {
            if *cached_stamp == stamp {
                return *counts;
            }
        }
    }
    let counts = match std::fs::read_to_string(path) {
        Ok(text) => (
            count_top_level_list(&text, "proxies"),
            count_top_level_list(&text, "proxy-groups"),
            count_top_level_list(&text, "rules"),
        ),
        Err(_) => (0, 0, 0),
    };
    if stamp != 0 {
        CACHE
            .get_or_init(|| Mutex::new(HashMap::new()))
            .lock()
            .unwrap()
            .insert(key, (stamp, counts));
    }
    counts
}

/// Renders one profile payload with real counters from its file.
pub fn profile_payload(st: &AppState, item: &Profile) -> Value {
    let expire_days = if item.expire > 0 {
        let remaining = (item.expire - now_secs()) / 86400;
        remaining.max(0)
    } else {
        0
    };
    let (used_share, used, total) = if item.total > 0 {
        let share = (item.used as f64 / item.total as f64).clamp(0.0, 1.0);
        (share, human_bytes(item.used), human_bytes(item.total))
    } else {
        (0.0, "0 B".to_string(), "0 B".to_string())
    };
    let path = profile_file(st, &item.id);
    let (proxies, groups, rules) = profile_counts(&path);
    json!({
        "id": item.id,
        "name": item.name,
        "type": item.ptype,
        "url": item.url,
        "updatedAt": human_age(item.updated_at),
        "interval": item.interval,
        "userAgent": item.user_agent,
        "timeout": item.timeout,
        "retry": item.retry,
        "lastError": item.last_error,
        "lastSuccess": item.last_success,
        "active": item.active,
        "expireDays": expire_days,
        "usedShare": used_share,
        "used": used,
        "total": total,
        "proxies": proxies,
        "groups": groups,
        "rules": rules,
    })
}

/// Derives a profile name from its URL (mirrors the Go import).
fn name_from_url(url: &str) -> String {
    let without_query = url.split('?').next().unwrap_or(url);
    let base = Path::new(without_query)
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("");
    let name = base
        .trim_end_matches(|c| c == '.')
        .rsplit_once('.')
        .map(|(stem, _)| stem)
        .unwrap_or(base);
    if name.is_empty() {
        "订阅".to_string()
    } else {
        name.to_string()
    }
}

/// Downloads (via curl) and stores a new profile. The stored file is always
/// converted YAML, never the raw subscription body.
pub async fn import_profile(
    st: &AppState,
    url: &str,
    user_agent: Option<&str>,
) -> Result<Profile, String> {
    validate_subscription_url(url)?;
    let (yaml, meta) = fetch_profile(&st.config_path(), url, user_agent, 45, 1).await?;
    let id = format!("p{}", std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0));

    std::fs::create_dir_all(st.profiles_dir())
        .map_err(|e| format!("mkdir profiles: {}", e))?;
    write_atomic(&profile_file(st, &id), yaml.as_bytes())
        .map_err(|e| format!("write profile: {}", e))?;

    let item = Profile {
        id: id.clone(),
        name: name_from_url(url),
        ptype: "url".into(),
        url: url.to_string(),
        updated_at: now_secs(),
        interval: meta.update_interval,
        used: meta.used,
        total: meta.total,
        expire: meta.expire,
        user_agent: user_agent.unwrap_or("").to_string(),
        timeout: 45,
        retry: 1,
        last_error: String::new(),
        last_success: now_secs(),
        active: false,
    };
    let mut list = load_profiles(st);
    list.push(item.clone());
    save_profiles(st, &list)?;
    Ok(item)
}

/// Re-downloads a URL profile; re-applies it when active (core is reloaded
/// or started, whichever the situation needs).
pub async fn update_profile(st: &AppState, id: &str) -> Result<Value, String> {
    if !valid_id(id) {
        return Err(format!("配置不存在: {}", id));
    }
    let list = load_profiles(st);
    let target = list
        .iter()
        .find(|p| p.id == id)
        .ok_or_else(|| format!("配置不存在: {}", id))?
        .clone();
    if target.url.is_empty() {
        return Err("该配置不是订阅,无法在线更新".into());
    }
    validate_subscription_url(&target.url)?;
    let ua = if target.user_agent.trim().is_empty() {
        None
    } else {
        Some(target.user_agent.as_str())
    };
    let timeout = if target.timeout >= 5 {
        target.timeout as u64
    } else {
        45
    };
    let retry = if target.retry >= 0 { target.retry } else { 1 };
    let fetched = fetch_profile(&st.config_path(), &target.url, ua, timeout, retry).await;
    let (yaml, meta) = match fetched {
        Ok(value) => value,
        Err(err) => {
            // Keep the old body and record the failure for the UI/cron.
            let mut list = load_profiles(st);
            for item in list.iter_mut() {
                if item.id == id {
                    item.last_error = err.clone();
                }
            }
            let _ = save_profiles(st, &list);
            return Err(err);
        }
    };
    write_atomic(&profile_file(st, id), yaml.as_bytes())
        .map_err(|e| format!("write profile: {}", e))?;

    let mut list = load_profiles(st);
    let mut was_active = false;
    for item in list.iter_mut() {
        if item.id == id {
            item.updated_at = now_secs();
            item.used = meta.used;
            item.total = meta.total;
            item.expire = meta.expire;
            if meta.update_interval > 0 {
                item.interval = meta.update_interval;
            }
            item.last_error.clear();
            item.last_success = now_secs();
            was_active = item.active;
        }
    }
    save_profiles(st, &list)?;

    if was_active {
        // Route through the same candidate + preflight + atomic rename path as
        // a manual apply; a bad subscription must not overwrite a working one.
        apply_profile(st, id).await?;
    }
    Ok(json!({"id": id, "updatedAt": now_secs(), "used": meta.used, "total": meta.total, "expire": meta.expire}))
}

/// Stores a user-provided YAML/share-link body as a local profile (no URL).
pub fn import_local(st: &AppState, name: &str, text: &str) -> Result<Profile, String> {
    if text.trim().is_empty() {
        return Err("配置内容为空".into());
    }
    if text.len() > 4 << 20 {
        return Err("配置内容过大".into());
    }
    let yaml = convert_subscription(&st.config_path(), text)?;
    let (errors, _) = crate::mixin::validate(&yaml);
    if !errors.is_empty() {
        return Err(format!("配置校验失败: {}", errors.join("；")));
    }
    let id = format!(
        "p{}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0)
    );
    std::fs::create_dir_all(st.profiles_dir())
        .map_err(|e| format!("mkdir profiles: {}", e))?;
    write_atomic(&profile_file(st, &id), yaml.as_bytes())?;
    let item = Profile {
        id: id.clone(),
        name: if name.trim().is_empty() {
            "本地配置".to_string()
        } else {
            name.trim().to_string()
        },
        ptype: "local".into(),
        url: String::new(),
        updated_at: now_secs(),
        interval: 0,
        user_agent: String::new(),
        timeout: 45,
        retry: 1,
        last_error: String::new(),
        last_success: now_secs(),
        ..Default::default()
    };
    let mut list = load_profiles(st);
    list.push(item.clone());
    save_profiles(st, &list)?;
    Ok(item)
}

/// Updates every URL profile sequentially and reports per-profile results.
pub async fn update_all(st: &AppState) -> Value {
    let list = load_profiles(st);
    let mut results = Vec::new();
    for item in list {
        if item.url.is_empty() {
            continue;
        }
        let outcome = update_profile(st, &item.id).await;
        results.push(serde_json::json!({
            "id": item.id,
            "name": item.name,
            "ok": outcome.is_ok(),
            "error": outcome.err().unwrap_or_default(),
        }));
    }
    serde_json::json!({"updated": results.len(), "results": results})
}

/// Edits profile metadata (name / url / auto-update interval in seconds).
pub fn patch_profile(st: &AppState, id: &str, patch: &Value) -> Result<(), String> {
    if !valid_id(id) {
        return Err(format!("配置不存在: {}", id));
    }
    let mut list = load_profiles(st);
    let mut found = false;
    for item in list.iter_mut() {
        if item.id == id {
            found = true;
            if let Some(v) = patch.get("name").and_then(|v| v.as_str()) {
                let v = v.trim();
                if !v.is_empty() {
                    item.name = v.to_string();
                }
            }
            if let Some(v) = patch.get("url").and_then(|v| v.as_str()) {
                let v = v.trim();
                if !v.is_empty() {
                    validate_subscription_url(v)?;
                }
                item.url = v.to_string();
                if !item.url.is_empty() {
                    item.ptype = "url".into();
                }
            }
            if let Some(v) = patch.get("interval").and_then(|v| v.as_i64()) {
                item.interval = v.max(0);
            }
            if let Some(v) = patch.get("userAgent").and_then(|v| v.as_str()) {
                if v.len() > 512 || v.chars().any(|c| c.is_control()) {
                    return Err("User-Agent 非法".into());
                }
                item.user_agent = v.trim().to_string();
            }
            if let Some(v) = patch.get("timeout").and_then(|v| v.as_i64()) {
                item.timeout = v.clamp(5, 300);
            }
            if let Some(v) = patch.get("retry").and_then(|v| v.as_i64()) {
                item.retry = v.clamp(0, 5);
            }
        }
    }
    if !found {
        return Err(format!("配置不存在: {}", id));
    }
    save_profiles(st, &list)
}

/// Activates a profile: converts (legacy raw profiles are healed here),
/// writes config.yaml atomically, then reloads or starts the core.
pub async fn apply_profile(st: &AppState, id: &str) -> Result<(), String> {
    if !valid_id(id) {
        return Err(format!("配置不存在: {}", id));
    }
    let path = profile_file(st, id);
    let data = std::fs::read_to_string(&path)
        .map_err(|_| format!("配置不存在: {}", id))?;
    let converted = crate::convert::convert_subscription(&st.config_path(), &data)
        .map_err(|e| format!("应用失败: {}", e))?;
    // User mixin (Nikki-style) is applied after conversion, before validation
    // and the atomic write, so the running config always includes it.
    let (final_yaml, touched) = crate::mixin::apply_mixin(&st.data_dir, &converted)
        .map_err(|e| format!("应用失败: {}", e))?;
    // Router-owned invariants win over subscription and user mixin.
    let final_yaml = crate::config::enforce_invariants(&final_yaml)
        .map_err(|e| format!("应用失败: {e}"))?;
    let (errors, _warnings) = crate::mixin::validate(&final_yaml);
    if !errors.is_empty() {
        return Err(format!("配置校验失败: {}", errors.join("；")));
    }

    // Never replace the live config until the core itself accepts the
    // candidate. The bundled IPC core has no `-t`, so preflight drives the
    // bridge's core.init/config.setup against a sanitised copy.
    let config_path = st.config_path();
    let candidate = config_path.with_file_name("config.yaml.candidate");
    let last_good = config_path.with_file_name("config.yaml.last-good");
    crate::config::write_atomic(&candidate, final_yaml.as_bytes())?;
    if let Err(err) = crate::preflight::validate_config(candidate.clone()).await {
        let _ = std::fs::remove_file(&candidate);
        return Err(format!("配置预检失败: {err}"));
    }
    if let Ok(previous) = std::fs::read(&config_path) {
        let _ = crate::config::write_atomic(&last_good, &previous);
    }
    std::fs::rename(&candidate, &config_path).map_err(|e| format!("应用配置失败: {e}"))?;
    if !touched.is_empty() {
        st.bus.publish(
            "system",
            "config.mixin",
            serde_json::json!({"profile": id, "keys": touched}),
        );
    }

    let mut list = load_profiles(st);
    for item in list.iter_mut() {
        item.active = item.id == id;
    }
    save_profiles(st, &list)?;

    reload_core(st).await;
    Ok(())
}

pub fn delete_profile(st: &AppState, id: &str) -> Result<(), String> {
    if !valid_id(id) {
        return Err(format!("配置不存在: {}", id));
    }
    let list: Vec<Profile> = load_profiles(st)
        .into_iter()
        .filter(|item| item.id != id)
        .collect();
    save_profiles(st, &list)?;
    let _ = std::fs::remove_file(profile_file(st, id));
    Ok(())
}

/// Waits for the controller to answer, then rolls back to
/// `config.yaml.last-good` if the freshly applied config never comes up.
/// The preflight rejects most bad configs, but a runtime-only failure (port
/// already in use, provider download, TUN permission) still needs a safety net.
async fn ensure_core(st: &AppState) {
    if wait_core(st, 15).await {
        return;
    }
    let config_path = st.config_path();
    let last_good = config_path.with_file_name("config.yaml.last-good");
    if !last_good.is_file() {
        return;
    }
    let Ok(previous) = std::fs::read(&last_good) else {
        return;
    };
    if crate::config::write_atomic(&config_path, &previous).is_err() {
        return;
    }
    eprintln!("flclash: new config did not come up; rolled back to config.yaml.last-good");
    let _ = service(st, "restart").await;
    let _ = wait_core(st, 10).await;
}

async fn wait_core(st: &AppState, seconds: u64) -> bool {
    for _ in 0..seconds * 2 {
        if crate::ctrl::core_reachable(st).await {
            return true;
        }
        tokio::time::sleep(std::time::Duration::from_millis(500)).await;
    }
    false
}

/// Applies config.yaml to a running core, or starts the core. This is why
/// "启用配置" works while the proxy is stopped.
pub async fn reload_core(st: &AppState) {
    let cfg_path = st.config_path();
    if crate::core::configured_core() == "sing-box" {
        // Keep the converted JSON in sync with the freshly applied
        // subscription. Validation uses the same `sing-box check` path as the
        // core switch; when it fails the previous (working) JSON is kept and
        // the restart below simply reuses it.
        match std::fs::read_to_string(&cfg_path) {
            Ok(yaml) => match crate::singbox::convert(&yaml) {
                Ok(json) => match crate::preflight::check_singbox_json(&json) {
                    Ok(()) => {
                        let _ = crate::config::write_atomic(
                            std::path::Path::new("/tmp/flclash-singbox.json"),
                            json.as_bytes(),
                        );
                    }
                    Err(err) => {
                        eprintln!("flclash: sing-box preflight failed, keeping previous JSON: {err}");
                    }
                },
                Err(err) => eprintln!("flclash: sing-box convert failed: {err}"),
            },
            Err(err) => eprintln!("flclash: read config.yaml failed: {err}"),
        }
        // sing-box's clash_api has no reload endpoint: listeners, route rules,
        // DNS and TUN only change with a process restart.
        let _ = service(st, "restart").await;
        ensure_core(st).await;
    } else if crate::config::file_config(&cfg_path).tun {
        // The native IPC core can drop TUN on controller PATCH/PUT updates.
        // Re-run listener.start with the complete config instead.
        let _ = service(st, "restart").await;
        ensure_core(st).await;
    } else {
        let reachable = crate::ctrl::ctrl_req(
            &st.controller,
            st.secret.as_deref(),
            "GET",
            "/version",
            None,
            std::time::Duration::from_secs(2),
        )
        .await;
        match reachable {
            Ok(reply) if reply.status < 500 => {
                let body = serde_json::json!({"path": st.config_path().display().to_string()});
                let put = crate::ctrl::ctrl_req(
                    &st.controller,
                    st.secret.as_deref(),
                    "PUT",
                    "/configs",
                    Some(&body.to_string()),
                    std::time::Duration::from_secs(15),
                )
                .await;
                if !matches!(&put, Ok(r) if r.status < 400) {
                    let _ = service(st, "restart").await;
                }
            }
            _ => {
                let _ = service(st, "start").await;
            }
        }
        ensure_core(st).await;
    }

    // A reload/restart swaps mihomo's fake-ip pool, but dnsmasq keeps serving
    // the old 198.18.x answers from its cache — LAN clients get RSTs for the
    // cache lifetime after every profile switch (looks like "switching broke
    // the network"). Flush both sides.
    let _ = crate::ctrl::ctrl_req(
        &st.controller,
        st.secret.as_deref(),
        "POST",
        "/cache/fakeip/flush",
        None,
        std::time::Duration::from_secs(5),
    )
    .await;
    let _ = tokio::process::Command::new("/etc/init.d/dnsmasq")
        .arg("restart")
        .output()
        .await;
}

/// Invokes the core init script (start/stop/restart).
pub async fn service(st: &AppState, action: &str) -> Result<(), String> {
    if !matches!(action, "start" | "stop" | "restart") {
        return Err(format!("未知操作: {}", action));
    }
    let output = tokio::process::Command::new(&st.init_script)
        .arg(action)
        .output()
        .await
        .map_err(|e| format!("{}: {}", action, e))?;
    // Keep interception, DNS and core liveness in the same state. stop uses
    // teardown so it works even while the old process is still exiting;
    // start/restart waits briefly and then rebuilds the requested mode.
    let proxy_action = if action == "stop" { "teardown" } else { "sync" };
    let _ = tokio::process::Command::new("/usr/libexec/flclash/proxy-rules.sh")
        .arg(proxy_action)
        .output()
        .await;
    if !output.status.success() {
        let text = format!(
            "{} {}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        return Err(format!("{}: {}", action, text.trim()));
    }
    Ok(())
}

/// Aggregated payload used by GET /profiles.
pub fn list_payload(st: &AppState) -> Value {
    let list = load_profiles(st);
    Value::Array(list.iter().map(|item| profile_payload(st, item)).collect())
}

